// Actual built React and Go TLS/session/C20 routes; authority/persistence in
// the loopback Go fixture is synthetic. No intercepted operation responses.
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { validOutput_preview_capture, validOutput_request_capture } from '../src/generated/validate-capture.js';

const [origin, mode] = process.argv.slice(2);
assert.equal(new URL(origin).protocol, 'https:');
assert.equal(new URL(origin).hostname, '127.0.0.1');
assert(['query', 'both'].includes(mode));
const browser = await chromium.launch({ headless: true, ...(process.env.ASSERVAT_CHROMIUM ? { executablePath: process.env.ASSERVAT_CHROMIUM } : {}) });
const context = await browser.newContext({ ignoreHTTPSErrors: true });
const page = await context.newPage();
const external = [], errors = [], calls = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (/violates.*Content Security Policy|Refused to (execute|apply|load)/i.test(message.text())) errors.push(message.text()); });
page.on('request', request => {
  const url = new URL(request.url());
  if (url.origin !== origin) external.push(request.url());
  if (url.pathname.startsWith('/api/v1/operations/')) calls.push({ name: url.pathname.split('/').at(-1), input: request.postDataJSON() });
});
const waitOperation = name => page.waitForResponse(response => new URL(response.url()).pathname === '/api/v1/operations/' + name && response.request().method() === 'POST');
const checked = async (response, validate) => {
  assert.equal(response.status(), 200);
  const request = response.request(), headers = await request.allHeaders();
  assert.equal(request.method(), 'POST');
  assert.equal(headers.origin, origin);
  assert.equal(headers['x-csrf-token'], 'C'.repeat(43));
  assert.equal(headers.authorization, undefined);
  const reply = await response.json();
  assert(validate(reply), 'actual Go response must satisfy generated browser contract');
  return reply;
};
try {
  await page.goto(origin + '/captures/new');
  await page.getByRole('link', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Collect evidence', exact: true })).toBeVisible();
  assert.equal(await page.evaluate(() => document.cookie), '');
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
  await page.getByLabel('Cluster ID', { exact: true }).fill('00000000-0000-4000-8000-000000000001');
  await page.getByLabel('Namespace', { exact: true }).fill('payments');
  await page.getByLabel('Workload or pod name', { exact: true }).fill('api');
  await page.getByRole('button', { name: 'Find diagnostics', exact: true }).click();
  const catalog = page.getByRole('region', { name: 'Capture profiles', exact: true });
  const profile = catalog.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Synthetic finite write arguments', exact: true }) });
  await expect(profile).toHaveCount(1);
  await profile.getByRole('button', { name: 'Add profile', exact: true }).click();
  const previewWait = waitOperation('preview_capture');
  await catalog.getByRole('button', { name: 'Review combined recording', exact: true }).click();
  const preview = await checked(await previewWait, validOutput_preview_capture);
  assert.equal(preview.status, 'ok');
  assert.equal(preview.data.approval_required, true);
  assert.equal(preview.data.capture_enabled, false);
  const choices = preview.data.result_access_actions;
  assert.equal(choices?.length, 1);
  assert.deepEqual(choices[0].operations, ['download_artifact', 'syscall_query']);
  assert.equal(preview.data.lifecycle_plan.actions.length, 1);
  assert.equal(choices[0].action_id, preview.data.lifecycle_plan.actions[0].actionID);
  const review = page.getByRole('region', { name: 'Collection review', exact: true });
  await review.getByLabel('Include follow-up access in this approval', { exact: true }).check();
  const operationChoice = review.getByRole('combobox', { name: 'Follow-up operations', exact: true });
  await expect(operationChoice.locator('option[value="' + mode + '"]')).toHaveText(mode === 'query' ? 'Saved syscall argument queries' : 'Downloads and saved syscall argument queries');
  await operationChoice.selectOption(mode);
  const maxBytes = mode === 'query' ? 49152 : 16 * 1024 * 1024;
  await review.getByLabel('Shared disclosure byte budget', { exact: true }).fill(String(maxBytes));
  await review.getByLabel('Follow-up operation limit', { exact: true }).fill('3');
  await review.getByLabel('Follow-up access period in seconds', { exact: true }).fill('3600');
  const firstWait = waitOperation('request_capture');
  await review.getByRole('button', { name: 'Request approval', exact: true }).click();
  const firstResponse = await firstWait;
  const pending = await checked(firstResponse, validOutput_request_capture);
  assert.equal(pending.status, 'error');
  assert.equal(pending.data.code, 'ApprovalRequired');
  const first = firstResponse.request().postDataJSON();
  assert.equal(first.preview_id, preview.data.preview_id);
  assert.equal(typeof first.idempotency_key, 'string');
  assert.deepEqual(first.result_access.actionIds, [choices[0].action_id]);
  assert.deepEqual(first.result_access.operations, mode === 'query' ? ['syscall_query'] : ['download_artifact', 'syscall_query']);
  assert.equal(first.result_access.maxArtifacts, 1);
  assert.equal(first.result_access.maxBytes, maxBytes);
  assert.equal(first.result_access.maxOperations, 3);
  assert.equal(first.result_access.clientIDs, undefined, 'C20 resolves the original authenticated console client');
  const until = Date.parse(first.result_access.notAfter);
  assert(until > Date.now() && until <= Date.now() + 3600_000);
  await expect(page.getByRole('link', { name: 'View approval', exact: true })).toHaveAttribute('href', '/approvals/00000000-0000-4000-8000-000000000041');
  const approved = await page.request.post(origin + '/test/argument-approve', { headers: { Origin: origin } });
  assert.equal(approved.status(), 204);
  const resumedWait = waitOperation('request_capture');
  await page.getByRole('button', { name: 'Continue after approval', exact: true }).click();
  const resumedResponse = await resumedWait;
  const accepted = await checked(resumedResponse, validOutput_request_capture);
  assert.equal(accepted.status, 'ok');
  assert.deepEqual(resumedResponse.request().postDataJSON(), first, 'approval resume must retain original body/key/absolute expiry');
  await page.waitForURL(/\/captures\/00000000-0000-4000-8000-000000000008$/);
  assert.equal(calls.filter(c => c.name === 'preview_capture').length, 1);
  assert.equal(calls.filter(c => c.name === 'request_capture').length, 2);
  assert.equal(calls.filter(c => ['syscall_query', 'get_query_result', 'prepare_artifact_download'].includes(c.name)).length, 0);
  assert.deepEqual(external, []);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ scope: 'compiled arguments capture authoring; synthetic authority, no acquisition', mode, previews: 1, requests: 2, currentClient: 'console', frozenApprovalResume: true }));
} finally {
  await context.close();
  await browser.close();
}

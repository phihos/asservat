type helmBundledIdentity struct {
	settings      contracts.SmallKeycloakSettings
	root          []byte
	consoleSecret string
	usersGroup    string
}

// These serving certificates are explicit owned-fixture operator input. The
// actual chart/services hook creates retained realm/client/group identities.
func newHelmBundledIdentity(t *testing.T, ctx context.Context, api kubernetes.Interface, d contracts.InitialBootstrap, nodeIP string, x helmBootstrapFixture) *helmBundledIdentity {
	t.Helper()
	if x.IdentityImage != contracts.SmallKeycloakImage {
		t.Fatal("actual selected chart Keycloak image unavailable")
	}
	root, cert, key := syntheticServingPair(t, nodeIP)
	tlsName := d.Name + "-operator-keycloak-tls"
	if _, err := api.CoreV1().Secrets(d.BootstrapNamespace).Create(ctx, &core.Secret{ObjectMeta: meta.ObjectMeta{Name: tlsName}, Type: core.SecretTypeTLS, Data: map[string][]byte{"tls.crt": cert, "tls.key": key}}, meta.CreateOptions{}); err != nil {
		t.Fatal("explicit operator Keycloak serving TLS", err)
	}
	return &helmBundledIdentity{root: root, settings: contracts.SmallKeycloakSettings{Namespace: d.BootstrapNamespace, SecretName: d.Name + "-keycloak-state", Hostname: "https://" + net.JoinHostPort(nodeIP, "31451"), Realm: "asservat", Origin: "https://" + net.JoinHostPort(nodeIP, "31450"), ConsoleClientID: "asservat-console", BrowserAudience: "asservat-api", MCPClientID: "asservat-mcp", MCPRedirectURIs: []string{"http://127.0.0.1:42000/callback"}, ProcessingOperators: true, Database: contracts.SmallKeycloakDatabase{Host: d.Name + "-postgres." + d.BootstrapNamespace + ".svc", Port: 5432, Database: "keycloak", Username: "keycloak"}}}
}

func (k *helmBundledIdentity) Values(t *testing.T, values map[string]any, input *contracts.InitialBootstrapInput, public *helmBundledPublic) {
	t.Helper()
	services := values["services"].(map[string]any)
	services["identity"] = map[string]any{"provider": "keycloak", "keycloak": map[string]any{"image": contracts.SmallKeycloakImage, "hostname": k.settings.Hostname, "realm": k.settings.Realm, "processingOperators": true, "tlsSecretName": input.Name + "-operator-keycloak-tls", "mcpRedirectURIs": k.settings.MCPRedirectURIs, "service": map[string]any{"type": "NodePort", "nodePort": 31451}}}
	b := values["bootstrap"].(map[string]any)
	// Numeric fleet/capacity settings are the shipped finite trial profile; no
	// fixture group or actor ID is inserted before product generation.
	fleet := helmContextTrialProfile(t).Fleet
	fleet.Issuer = k.settings.Hostname + "/realms/" + k.settings.Realm
	fleet.Clients = []string{k.settings.ConsoleClientID, k.settings.MCPClientID}
	fleet.Groups = []string{}
	raw, _ := json.Marshal(fleet)
	var f map[string]any
	json.Unmarshal(raw, &f)
	b["fleet"] = f
	b["continuation"] = public.Values(t, k)
	input.Fleet = fleet
	input.IdentitySource = "bundledKeycloak"
}

func (k *helmBundledIdentity) Resolve(t *testing.T, ctx context.Context, api kubernetes.Interface, input *contracts.InitialBootstrapInput, f *fixture) *installedIdentity {
	t.Helper()
	source, err := api.CoreV1().Secrets(k.settings.Namespace).Get(ctx, k.settings.SecretName, meta.GetOptions{})
	if err != nil || bootstrap.ValidateSmallKeycloakMaterial(k.settings, source) != nil || source.UID == "" || source.ResourceVersion == "" {
		t.Fatal("actual original retained Keycloak material", err)
	}
	k.usersGroup = string(source.Data[contracts.SmallKeycloakUsersGroup])
	k.consoleSecret = string(source.Data[contracts.SmallKeycloakConsoleSecret])
	input.Fleet.Groups = []string{k.usersGroup}
	input.IdentitySource = ""
	f.Identity = &struct{ Base, RootCA, AdminUser, AdminPassword, UserPassword string }{k.settings.Hostname, string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: k.root})), string(source.Data[contracts.SmallKeycloakAdminUsername]), string(source.Data[contracts.SmallKeycloakAdminPassword]), "synthetic-bundled-user-password-not-a-default"}
	// The source is generated by the product; only deliberate fixture humans
	// and memberships are created by this attachment.
	identity := newInstalledBundledIdentity(t, *f, k.settings, k.usersGroup, k.consoleSecret, true)
	for _, raw := range source.Data {
		clear(raw)
	}
	return identity
}

func bundledKeycloakIssuer(s contracts.SmallKeycloakSettings) string {
	return strings.TrimSuffix(s.Hostname, "/") + "/realms/" + s.Realm
}

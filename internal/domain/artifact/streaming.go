package artifact

import "time"

// ADR-166 qualification bounds, raised by ADR-244 from 128 MiB to 256 MiB, the
// largest S-04 frozen recording ceiling. Not a product size limit: larger
// native limits need their own part-size and resource qualification. 256 MiB
// plus 32 frames of cipher overhead needs 33 parts of 8 MiB.
const (
	StreamingNativeLimit int64 = 256 << 20
	StreamingPartBytes   int64 = 8 << 20
	StreamingMaxParts          = 33
)

// StreamingPlan extends one storage obligation above a single frame. It grants
// no acquisition or disclosure. WriterEpoch names the accepted original writer
// process; it is not generated by an upload caller after a failed start.
type StreamingPlan struct {
	Registration Registration
	WriterEpoch  string
}

func (p StreamingPlan) Validate() error {
	r := p.Registration
	if r.Validate() != nil || r.NativeLimit <= FrameBytes || r.NativeLimit > StreamingNativeLimit || !uuid(p.WriterEpoch) || p.PartLimit() > StreamingMaxParts {
		return ErrInvalid
	}
	return nil
}

// TemporaryBytes conservatively charges a second complete data ceiling for
// unfinished or uncertain multipart parts until cleanup proves absence.
func (p StreamingPlan) TemporaryBytes() int64 { return p.Registration.Limits()[0] }

func (p StreamingPlan) PartLimit() int {
	return int((p.TemporaryBytes() + StreamingPartBytes - 1) / StreamingPartBytes)
}

func (p StreamingPlan) Equal(o StreamingPlan) bool {
	return p.WriterEpoch == o.WriterEpoch && p.Registration.Equal(o.Registration)
}

// StreamingPart is one exact ciphertext part; ETag is set when acknowledged.
type StreamingPart struct {
	Number int
	Bytes  int64
	SHA256 Digest
	ETag   string `json:",omitempty"`
}

func streamingText(s string) bool {
	if len(s) < 1 || len(s) > 1024 {
		return false
	}
	for _, b := range []byte(s) {
		if b < 32 || b == 127 {
			return false
		}
	}
	return true
}

// StreamingState holds ciphertext metadata only. Spent claims stay spent: a
// read or retry can never return a fresh create/complete permit.
type StreamingState struct {
	CreateSpent    bool            `json:",omitempty"`
	UploadID       string          `json:",omitempty"`
	Parts          []StreamingPart `json:",omitempty"`
	CompleteSpent  bool            `json:",omitempty"`
	CompleteBytes  int64           `json:",omitempty"`
	CompleteSHA256 Digest          `json:",omitzero"`
	Receipt        *CopyReceipt    `json:",omitempty"`
	Aborted        bool            `json:",omitempty"`
	ReleasedAt     time.Time       `json:",omitzero"`
}

func (s StreamingState) Validate(p StreamingPlan) error {
	if p.Validate() != nil || len(s.Parts) > p.PartLimit() {
		return ErrInvalid
	}
	if !s.CreateSpent && (s.UploadID != "" || len(s.Parts) != 0 || s.CompleteSpent) {
		return ErrInvalid
	}
	if s.UploadID != "" && !streamingText(s.UploadID) || len(s.Parts) > 0 && s.UploadID == "" {
		return ErrInvalid
	}
	var total int64
	for i, x := range s.Parts {
		last := i == len(s.Parts)-1
		if x.Number != i+1 || x.Bytes < 1 || x.Bytes > StreamingPartBytes || x.SHA256 == (Digest{}) || x.ETag != "" && !streamingText(x.ETag) || !last && (x.Bytes != StreamingPartBytes || x.ETag == "") {
			return ErrInvalid
		}
		total += x.Bytes
	}
	if total > p.TemporaryBytes() {
		return ErrLimit
	}
	if s.CompleteSpent {
		if len(s.Parts) == 0 || s.Parts[len(s.Parts)-1].ETag == "" || s.CompleteBytes != total || s.CompleteSHA256 == (Digest{}) {
			return ErrInvalid
		}
	} else if s.CompleteBytes != 0 || s.CompleteSHA256 != (Digest{}) || s.Receipt != nil {
		return ErrInvalid
	}
	if r := s.Receipt; r != nil && (!streamingText(r.VersionID) || r.VersionID == "null" || !streamingText(r.ETag) || r.Bytes != s.CompleteBytes || r.SHA256 != s.CompleteSHA256) {
		return ErrInvalid
	}
	// Temporary obligations are released only after a verified final object or
	// an abort whose absence the adapter's inventory independently proved.
	if !s.ReleasedAt.IsZero() && s.Receipt == nil && !s.Aborted {
		return ErrInvalid
	}
	return nil
}

type StreamingStepKind string

const (
	StreamClaimCreate   StreamingStepKind = "claim-create"
	StreamUpload        StreamingStepKind = "upload"
	StreamClaimPart     StreamingStepKind = "claim-part"
	StreamAckPart       StreamingStepKind = "ack-part"
	StreamClaimComplete StreamingStepKind = "claim-complete"
	StreamAckComplete   StreamingStepKind = "ack-complete"
	StreamRelease       StreamingStepKind = "release"
)

type StreamingStep struct {
	Kind     StreamingStepKind
	UploadID string
	Part     StreamingPart
	Bytes    int64
	SHA256   Digest
	Receipt  CopyReceipt
	Aborted  bool      // release only: the inventory proved abort and absence
	At       time.Time // release only
}

// Advance applies one journal transition. fresh is true only for a newly
// spent create/part/complete claim; the adapter must withhold the remote
// request on any commit uncertainty, cancellation or elapsed deadline.
func (s StreamingState) Advance(p StreamingPlan, x StreamingStep) (next StreamingState, fresh bool, err error) {
	if s.Validate(p) != nil || !s.ReleasedAt.IsZero() {
		return s, false, ErrInvalid
	}
	next = s
	next.Parts = append([]StreamingPart(nil), s.Parts...)
	switch x.Kind {
	case StreamClaimCreate:
		if s.CreateSpent {
			return s, false, nil
		}
		next.CreateSpent, fresh = true, true
	case StreamUpload:
		if !s.CreateSpent || !streamingText(x.UploadID) {
			return s, false, ErrInvalid
		}
		if s.UploadID != "" {
			if s.UploadID != x.UploadID {
				return s, false, ErrIntegrity
			}
			return s, false, nil
		}
		next.UploadID = x.UploadID
	case StreamClaimPart:
		n := x.Part.Number
		if s.UploadID == "" || s.CompleteSpent || x.Part.ETag != "" || n < 1 || x.Part.Bytes < 1 || x.Part.Bytes > StreamingPartBytes || x.Part.SHA256 == (Digest{}) {
			return s, false, ErrInvalid
		}
		if n <= len(s.Parts) {
			old := s.Parts[n-1]
			old.ETag = ""
			if old != x.Part {
				return s, false, ErrIntegrity
			}
			return s, false, nil
		}
		if n != len(s.Parts)+1 || n > p.PartLimit() || len(s.Parts) > 0 && (s.Parts[len(s.Parts)-1].ETag == "" || s.Parts[len(s.Parts)-1].Bytes != StreamingPartBytes) {
			return s, false, ErrInvalid
		}
		next.Parts = append(next.Parts, x.Part)
		fresh = true
	case StreamAckPart:
		n := x.Part.Number
		if s.CompleteSpent || n < 1 || n > len(s.Parts) || !streamingText(x.Part.ETag) {
			return s, false, ErrInvalid
		}
		old := s.Parts[n-1]
		if old.Bytes != x.Part.Bytes || old.SHA256 != x.Part.SHA256 || old.ETag != "" && old.ETag != x.Part.ETag {
			return s, false, ErrIntegrity
		}
		next.Parts[n-1] = x.Part
	case StreamClaimComplete:
		if s.CompleteSpent {
			if s.CompleteBytes != x.Bytes || s.CompleteSHA256 != x.SHA256 {
				return s, false, ErrIntegrity
			}
			return s, false, nil
		}
		next.CompleteSpent, next.CompleteBytes, next.CompleteSHA256, fresh = true, x.Bytes, x.SHA256, true
	case StreamAckComplete:
		if !s.CompleteSpent {
			return s, false, ErrInvalid
		}
		receipt := x.Receipt
		if s.Receipt != nil && *s.Receipt != receipt {
			return s, false, ErrIntegrity
		}
		next.Receipt = &receipt
	case StreamRelease:
		if x.At.IsZero() || !x.Aborted && s.Receipt == nil {
			return s, false, ErrInvalid
		}
		next.Aborted, next.ReleasedAt = x.Aborted, x.At
	default:
		return s, false, ErrInvalid
	}
	if err = next.Validate(p); err != nil {
		return s, false, err
	}
	return next, fresh, nil
}

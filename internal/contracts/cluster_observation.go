package contracts

import (
	"bytes"
	"errors"
)

// These are private, purpose-fixed read messages. Decoding one grants neither
// producer authority nor a fresh observation; concrete authenticated consumers
// retain the original request and every returned source interval.
const (
	ClusterObservationFormat         = "cluster-observation/v1"
	ClusterObservationBytes          = 192 << 10
	ClusterObservationPageSize       = 64
	ClusterObservationCursorBytes    = 8192
	ClusterObservationSelectorKeys   = 256
	ClusterObservationNamespaceGuard = "capacity-namespace-guard"
	ClusterObservationNamespaces     = "capacity-namespace-candidates"
	ClusterObservationWorkloads      = "capacity-workload-candidates"
	ClusterObservationWorkload       = "capacity-workload"
	// ClusterObservationGuardedWorkload is one observation of the namespace
	// guard and then one workload under its keys (ADR-197): a regional
	// reconcile's guard and workload in one five-second window.
	ClusterObservationGuardedWorkload = "capacity-guarded-workload"
)

var ErrClusterObservationProtocol = errors.New("invalid cluster observation message")

type ClusterObservationNamespace struct {
	Name string `json:"name"`
	UID  string `json:"uid"`
}

type ClusterObservationWorkloadRef struct {
	Kind string `json:"kind"`
	Name string `json:"name"`
	UID  string `json:"uid"`
}

// RequestID and Challenge are generated by the actual initiating owner. The
// transport additionally binds this request to its exact admitted connection;
// these strings cannot claim another process, socket or authority interval.
type ClusterObservationRequest struct {
	Format      string                         `json:"format"`
	RequestID   string                         `json:"requestId"`
	Challenge   string                         `json:"challenge"`
	RootID      string                         `json:"rootId"`
	ClusterID   string                         `json:"clusterId"`
	Purpose     string                         `json:"purpose"`
	RequestedAt string                         `json:"requestedAt"`
	NotAfter    string                         `json:"notAfter"`
	Namespace   *ClusterObservationNamespace   `json:"namespace,omitempty"`
	Workload    *ClusterObservationWorkloadRef `json:"workload,omitempty"`
	Kind        string                         `json:"kind,omitempty"`
	Keys        []string                       `json:"keys,omitempty"`
	Continue    string                         `json:"continue,omitempty"`
}

type ClusterObservationInterval struct {
	ObservedAt string `json:"observedAt"`
	FreshUntil string `json:"freshUntil"`
}

type ClusterObservationGuard struct {
	Digest   string                     `json:"digest"`
	Keys     []string                   `json:"keys"`
	Interval ClusterObservationInterval `json:"interval"`
}

type ClusterObservationNamespacePage struct {
	ResourceVersion string                        `json:"resourceVersion"`
	Continue        string                        `json:"continue"`
	Items           []ClusterObservationNamespace `json:"items"`
}

type ClusterObservationWorkloadPage struct {
	ResourceVersion string                          `json:"resourceVersion"`
	Continue        string                          `json:"continue"`
	Items           []ClusterObservationWorkloadRef `json:"items"`
}

type ClusterObservationExactWorkload struct {
	Namespace                ClusterObservationNamespace   `json:"namespace"`
	NamespaceResourceVersion string                        `json:"namespaceResourceVersion"`
	Labels                   map[string]string             `json:"labels"`
	NamespaceInterval        ClusterObservationInterval    `json:"namespaceInterval"`
	Workload                 ClusterObservationWorkloadRef `json:"workload"`
	WorkloadResourceVersion  string                        `json:"workloadResourceVersion"`
	Interval                 ClusterObservationInterval    `json:"interval"`
}

// A result has exactly the member selected by the original request's closed
// purpose. The application enforces that union and exact request digest before
// any port value exists. Candidate pages are never absence or effect proofs.
// Unavailable replies are transport errors, never empty successful pages.
type ClusterObservationResult struct {
	Format        string                           `json:"format"`
	RequestID     string                           `json:"requestId"`
	Challenge     string                           `json:"challenge"`
	RootID        string                           `json:"rootId"`
	ClusterID     string                           `json:"clusterId"`
	Purpose       string                           `json:"purpose"`
	RequestDigest string                           `json:"requestDigest"`
	Interval      ClusterObservationInterval       `json:"interval"`
	Guard         *ClusterObservationGuard         `json:"guard,omitempty"`
	Namespaces    *ClusterObservationNamespacePage `json:"namespaces,omitempty"`
	Workloads     *ClusterObservationWorkloadPage  `json:"workloads,omitempty"`
	Workload      *ClusterObservationExactWorkload `json:"workload,omitempty"`
}

func EncodeClusterObservationRequest(v ClusterObservationRequest) ([]byte, error) {
	b, e := canonicalAPIContext(v, ClusterObservationBytes)
	if e != nil {
		return nil, ErrClusterObservationProtocol
	}
	return b, nil
}

func DecodeClusterObservationRequest(b []byte) (ClusterObservationRequest, error) {
	v, e := decodeClosedRPC[ClusterObservationRequest](bytes.NewReader(b), ClusterObservationBytes)
	if e != nil {
		return ClusterObservationRequest{}, ErrClusterObservationProtocol
	}
	return v, nil
}

func EncodeClusterObservationResult(v ClusterObservationResult) ([]byte, error) {
	b, e := canonicalAPIContext(v, ClusterObservationBytes)
	if e != nil {
		return nil, ErrClusterObservationProtocol
	}
	return b, nil
}

func DecodeClusterObservationResult(b []byte) (ClusterObservationResult, error) {
	v, e := decodeClosedRPC[ClusterObservationResult](bytes.NewReader(b), ClusterObservationBytes)
	if e != nil {
		return ClusterObservationResult{}, ErrClusterObservationProtocol
	}
	return v, nil
}
